import queue
import threading
import hashlib
import time

class NullZoneIngestionMatrix:
    def __init__(self):
        self.raw_data_queue = queue.Queue()  # Input queue for raw data
        self.processed_metadata = queue.Queue() # Output queue for processed metadata
        self.running = False
        self.worker_thread = None
        print("[NullZoneIngestionMatrix] Initialized: Ready for data ingestion.")

    def start_ingestion_processor(self):
        if not self.running:
            self.running = True
            self.worker_thread = threading.Thread(target=self._ingestion_loop)
            self.worker_thread.daemon = True # Allow program to exit even if thread is running
            self.worker_thread.start()
            print("[NullZoneIngestionMatrix] Ingestion processor started.")

    def stop_ingestion_processor(self):
        if self.running:
            self.running = False
            self.worker_thread.join()
            print("[NullZoneIngestionMatrix] Ingestion processor stopped.")

    def _ingestion_loop(self):
        while self.running:
            if not self.raw_data_queue.empty():
                raw_data = self.raw_data_queue.get()
                self._process_data_pipeline(raw_data)
            else:
                time.sleep(0.01) # Small delay to prevent busy-waiting

    def ingest_raw_data(self, data_id, data_payload):
        """Receives raw data for processing."""
        print(f"[NullZoneIngestionMatrix] Ingesting raw data for ID: {data_id}")
        self.raw_data_queue.put({'id': data_id, 'payload': data_payload})

    def _process_data_pipeline(self, data):
        """Simulates the multi-stage data processing pipeline."""
        data_id = data['id']
        payload = data['payload']

        # 1. Active Silicon Landing Zone (Shredder)
        shredded_data = self._shredder(payload)
        print(f"  [ASLZ] Data {data_id} shredded.")

        # 2. Crushing Fins (Structural Signature)
        signature = self._calculate_structural_signature(shredded_data)
        print(f"  [CF] Structural signature for {data_id}: {signature[:10]}...")

        # 3. Metal-1 Output Path (AI Security Check)
        metadata = self._ai_security_check(data_id, payload, signature)
        print(f"  [M1OP] Metadata for {data_id} generated: {metadata['status']}")

        self.processed_metadata.put(metadata)

    def _shredder(self, payload):
        """Simulates hardware clock cycles by mixing and scrambling the data."""
        # Very basic simulation: just a hash that mixes the payload content
        return hashlib.sha256(payload.encode()).hexdigest()

    def _calculate_structural_signature(self, shredded_data):
        """Calculates a structural signature (SHA256 hash)."""
        return hashlib.sha256(shredded_data.encode()).hexdigest()

    def _ai_security_check(self, data_id, original_payload, signature):
        """Performs AI-based security checks for malicious keywords."""
        if "exploit" in original_payload.lower() or \
           "bypass" in original_payload.lower() or \
           "malware" in original_payload.lower():
            return {
                'id': data_id,
                'status': 'MALICIOUS_FLAGGED',
                'signature': signature,
                'reason': 'AI detected malicious pattern'
            }
        else:
            return {
                'id': data_id,
                'status': 'CLEAN_VERIFIED',
                'signature': signature,
                'reason': 'AI verified clean data'
            }

